@lru_cache(maxsize=4)
def street_pool(seed: int) -> list[str]:
    fk = Faker("en_US")
    fk.seed_instance(seed)
    return [f"{fk.building_number()}/{fk.random_int(1, 40)}" for _ in range(500)]
